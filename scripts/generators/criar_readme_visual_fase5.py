from __future__ import annotations

import shutil
from pathlib import Path


ROOT = Path.cwd()


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.strip() + "\n", encoding="utf-8")
    print(f"[OK] escrito: {path}")


def copy_if_exists(src: Path, dst: Path) -> bool:
    if src.exists():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        print(f"[OK] copiado: {src} -> {dst}")
        return True
    print(f"[AVISO] não encontrado, ignorado: {src}")
    return False


def backup_readme() -> None:
    current = ROOT / "README.md"
    backup = ROOT / "README.before-phase5.md"

    if current.exists() and not backup.exists():
        shutil.copy2(current, backup)
        print(f"[OK] backup criado: {backup}")
    elif backup.exists():
        print("[INFO] README.before-phase5.md já existe; backup preservado.")
    else:
        print("[INFO] README.md ainda não existe; nenhum backup criado.")


def collect_preview_assets() -> list[str]:
    source_dir = ROOT / "outputs" / "case12" / "figures"
    target_dir = ROOT / "assets" / "preview"

    candidates = [
        "case12_panel.png",
        "case12_u.png",
        "case12_v.png",
        "case12_psi.png",
        "case12_wz.png",
        "case12_txx.png",
        "case12_txy.png",
        "case12_tyy.png",
    ]

    copied: list[str] = []
    for name in candidates:
        if copy_if_exists(source_dir / name, target_dir / name):
            copied.append(f"assets/preview/{name}")

    return copied


