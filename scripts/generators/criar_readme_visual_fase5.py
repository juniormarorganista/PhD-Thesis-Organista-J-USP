def ensure_gitignore() -> None:
    gitignore = ROOT / ".gitignore"
    existing = gitignore.read_text(encoding="utf-8") if gitignore.exists() else ""

    additions = [
        "",
        "# Generated outputs",
        "outputs/",
        "",
        "# Python",
        "__pycache__/",
        "*.py[cod]",
        "*.egg-info/",
        ".pytest_cache/",
        ".mypy_cache/",
        ".ruff_cache/",
        ".venv/",
        "",
        "# OS/editor",
        ".DS_Store",
        "Thumbs.db",
        ".vscode/",
    ]

    changed = False
    for line in additions:
        if line and line not in existing:
            existing += line + "\n"
            changed = True

    if changed or not gitignore.exists():
        gitignore.write_text(existing.strip() + "\n", encoding="utf-8")
        print(f"[OK] atualizado: {gitignore}")
    else:
        print("[INFO] .gitignore já contém entradas principais.")


