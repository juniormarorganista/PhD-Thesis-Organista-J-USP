"""Regression tests for the compact 4th-order derivatives against Fortran.

The reference CSVs are generated by
``validation/fortran_reference/case_compact_derivatives/case_compact_derivatives_reference.f90``,
which mirrors ``coef_4a``/``coeff_4a``/``rhsx_4a``/``rhsxx_4a``/``rhsy_4a``/
``rhsyy_4a`` (``derivs.f``) and ``tridx``/``tridy`` (``solvers.f``) applied to
``f(x, y) = sin(pi*x) * cos(pi*y)``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from mms_viscoelastic.io.reference import read_reference_csv
from mms_viscoelastic.numerics.derivatives import (
    compact_derivative_x,
    compact_derivative_y,
    compact_second_derivative_x,
    compact_second_derivative_y,
)

REFERENCE_DIR = Path("validation") / "reference_data"


def _load_grid(path: Path) -> tuple[pd.DataFrame, int, int, float, float]:
    df = read_reference_csv(path)
    x_unique = np.sort(df["x"].unique())
    y_unique = np.sort(df["y"].unique())
    nx = len(x_unique)
    ny = len(y_unique)
    assert nx * ny == len(df)
    dx = float(x_unique[1] - x_unique[0])
    dy = float(y_unique[1] - y_unique[0])
    return df, nx, ny, dx, dy


@pytest.mark.parametrize("size", [9, 17])
def test_compact_derivatives_match_fortran_reference(size: int) -> None:
    path = REFERENCE_DIR / f"case_compact_derivatives_{size}x{size}_default.csv"
    df, nx, ny, dx, dy = _load_grid(path)

    f = df["f"].to_numpy(dtype=float).reshape(ny, nx)

    num_dfdx = df["num_dfdx"].to_numpy(dtype=float).reshape(ny, nx)
    num_d2fdx2 = df["num_d2fdx2"].to_numpy(dtype=float).reshape(ny, nx)
    num_dfdy = df["num_dfdy"].to_numpy(dtype=float).reshape(ny, nx)
    num_d2fdy2 = df["num_d2fdy2"].to_numpy(dtype=float).reshape(ny, nx)

    assert np.max(np.abs(compact_derivative_x(f, dx) - num_dfdx)) < 1.0e-10
    assert np.max(np.abs(compact_second_derivative_x(f, dx) - num_d2fdx2)) < 1.0e-10
    assert np.max(np.abs(compact_derivative_y(f, dy) - num_dfdy)) < 1.0e-10
    assert np.max(np.abs(compact_second_derivative_y(f, dy) - num_d2fdy2)) < 1.0e-10


def test_compact_first_derivative_is_fourth_order_everywhere() -> None:
    """The first-derivative closure is 4th-order everywhere, including the boundary.

    Checked by halving h (9x9 -> 17x17) and confirming the global max error
    drops by a factor close to 2^4 = 16, rather than pinning the absolute
    error to an arbitrary constant.
    """
    path_coarse = REFERENCE_DIR / "case_compact_derivatives_9x9_default.csv"
    path_fine = REFERENCE_DIR / "case_compact_derivatives_17x17_default.csv"

    df_coarse, nx_c, ny_c, dx_c, _ = _load_grid(path_coarse)
    df_fine, nx_f, ny_f, dx_f, _ = _load_grid(path_fine)

    f_coarse = df_coarse["f"].to_numpy(dtype=float).reshape(ny_c, nx_c)
    f_fine = df_fine["f"].to_numpy(dtype=float).reshape(ny_f, nx_f)
    exact_coarse = df_coarse["exact_dfdx"].to_numpy(dtype=float).reshape(ny_c, nx_c)
    exact_fine = df_fine["exact_dfdx"].to_numpy(dtype=float).reshape(ny_f, nx_f)

    error_coarse = np.max(np.abs(compact_derivative_x(f_coarse, dx_c) - exact_coarse))
    error_fine = np.max(np.abs(compact_derivative_x(f_fine, dx_f) - exact_fine))

    observed_order = np.log2(error_coarse / error_fine)
    assert 3.5 < observed_order < 4.5


def test_compact_second_derivative_boundary_is_third_order_not_fourth() -> None:
    """Documents the boundary-closure truncation order verified symbolically.

    ``f_1'' + 11 f_2'' = (39f_1-81f_2+45f_3-3f_4)/(3h^2)`` has a residual of
    ``(1/12) h^3 f^(5)`` when the exact solution is substituted -- one order
    below the interior O(h^4) stencil. Halving h should roughly halve this
    boundary error (order ~1), not divide it by ~16 (order ~4).
    """
    path_coarse = REFERENCE_DIR / "case_compact_derivatives_9x9_default.csv"
    path_fine = REFERENCE_DIR / "case_compact_derivatives_17x17_default.csv"

    df_coarse, nx_c, ny_c, dx_c, _ = _load_grid(path_coarse)
    df_fine, nx_f, ny_f, dx_f, _ = _load_grid(path_fine)

    f_coarse = df_coarse["f"].to_numpy(dtype=float).reshape(ny_c, nx_c)
    f_fine = df_fine["f"].to_numpy(dtype=float).reshape(ny_f, nx_f)
    exact_coarse = df_coarse["exact_d2fdx2"].to_numpy(dtype=float).reshape(ny_c, nx_c)
    exact_fine = df_fine["exact_d2fdx2"].to_numpy(dtype=float).reshape(ny_f, nx_f)

    error_coarse_boundary = abs(compact_second_derivative_x(f_coarse, dx_c)[0, 0] - exact_coarse[0, 0])
    error_fine_boundary = abs(compact_second_derivative_x(f_fine, dx_f)[0, 0] - exact_fine[0, 0])

    ratio = error_coarse_boundary / error_fine_boundary
    observed_order = np.log2(ratio)
    assert 2.5 < observed_order < 3.5
