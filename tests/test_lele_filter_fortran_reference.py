"""Regression tests for the Lele compact filter against Fortran.

The reference CSVs are generated by
``validation/fortran_reference/case_lele_filter/case_lele_filter_reference.f90``,
which mirrors ``rhs_tridfx_wz``/``rhs_tridfy_wz``/``lhs_tridfx``/``lhs_tridfy``
(``loop.f``) and ``tridx``/``tridy`` (``solvers.f``) applied to
``f(x, y) = sin(3*pi*x) * cos(2*pi*y) + 0.1*sin(20*pi*x)`` with the default
``alphaf = 0.48`` from ``par.nn``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from mms_viscoelastic.io.reference import read_reference_csv
from mms_viscoelastic.numerics.filters import DEFAULT_ALPHA_F, lele_filter_x, lele_filter_y

REFERENCE_DIR = Path("validation") / "reference_data"


@pytest.mark.parametrize("size", [13, 21])
def test_lele_filter_matches_fortran_reference(size: int) -> None:
    path = REFERENCE_DIR / f"case_lele_filter_{size}x{size}_default.csv"
    df = read_reference_csv(path)

    x_unique = np.sort(df["x"].unique())
    y_unique = np.sort(df["y"].unique())
    nx = len(x_unique)
    ny = len(y_unique)
    assert nx * ny == len(df)

    f = df["f"].to_numpy(dtype=float).reshape(ny, nx)
    filtered_x_reference = df["filtered_x"].to_numpy(dtype=float).reshape(ny, nx)
    filtered_y_reference = df["filtered_y"].to_numpy(dtype=float).reshape(ny, nx)

    filtered_x = lele_filter_x(f, alpha_f=DEFAULT_ALPHA_F)
    filtered_y = lele_filter_y(f, alpha_f=DEFAULT_ALPHA_F)

    assert np.max(np.abs(filtered_x - filtered_x_reference)) < 1.0e-10
    assert np.max(np.abs(filtered_y - filtered_y_reference)) < 1.0e-10
