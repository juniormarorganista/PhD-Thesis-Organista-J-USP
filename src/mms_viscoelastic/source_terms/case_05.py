def evaluate_case_05_source_terms(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case05SourceTermParameters | None = None,
) -> Case05SourceTerms:
    """Evaluate all Case 05 source terms."""
    return Case05SourceTerms(
        tfwz=evaluate_case_05_tfwz(grid, t=t, parameters=parameters),
        tfTxx=evaluate_case_05_tftxx(grid, t=t, parameters=parameters),
        tfTxy=evaluate_case_05_tftxy(grid, t=t, parameters=parameters),
        tfTyy=evaluate_case_05_tftyy(grid, t=t, parameters=parameters),
    )


