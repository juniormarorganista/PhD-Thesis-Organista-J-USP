"""Source terms for MMS Case 03.

This module ports the algebraic source terms from the original Fortran
routine:

``src/fortran_original/4Order_LPOG_Euler/case_03.f::source_term_case_03(t)``

The velocity/vorticity fields driving the convective terms are the same
polynomial family as cases 01/02. The polymeric stress ansatz is the same
trigonometric form as case 12
(``a1 + a3 cos(pi x) + a2 sin(pi x)`` times ``b1 + b3 cos(pi y) + b2 sin(pi
y)``).

Transcription method
---------------------
Given the density of these expressions (~130-225 parenthesis pairs each),
each source term was generated by a mechanical script that strips the
Fortran77 continuation prefix, renames intrinsics (``dcos``/``Sin``/``dexp``
-> ``np.cos``/``np.sin``/``np.exp``, ``pii`` -> ``np.pi``) and splits the
result into its top-level additive terms (``term_1``, ``term_2``, ...),
copied verbatim rather than retyped by hand. Each function's terms are
summed in the same order and with the same signs as the original Fortran
right-hand side.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import NDArray

from mms_viscoelastic.grids import Grid2D

FloatArray = NDArray[np.float64]

CASE03_FORTRAN_ARRAYS: tuple[str, ...] = ("tfwz", "tfTxx", "tfTxy", "tfTyy")


@dataclass(frozen=True)
class Case03SourceTermParameters:
    """Physical and constitutive parameters required by Case 03 source terms."""

    reynolds: float = 1.0
    wi: float = 1.0
    beta: float = 0.5
    epsilon: float = 0.0
    xi: float = 0.0
    alpha_g: float = 0.0
    at: float = 0.0

    a1xx: float = 1.0
    a2xx: float = 1.0
    a3xx: float = 1.0
    b1xx: float = 1.0
    b2xx: float = 1.0
    b3xx: float = 1.0

    a1xy: float = 1.0
    a2xy: float = 1.0
    a3xy: float = 1.0
    b1xy: float = 1.0
    b2xy: float = 1.0
    b3xy: float = 1.0

    a1yy: float = 1.0
    a2yy: float = 1.0
    a3yy: float = 1.0
    b1yy: float = 1.0
    b2yy: float = 1.0
    b3yy: float = 1.0

    def validate(self) -> None:
        """Validate parameters needed by the ported source terms."""
        if self.reynolds == 0.0:
            raise ValueError("reynolds must be nonzero.")
        if self.wi == 0.0:
            raise ValueError("wi must be nonzero.")
        if not np.isfinite(self.beta):
            raise ValueError("beta must be finite.")


@dataclass(frozen=True)
class Case03SourceTerms:
    """Container for MMS Case 03 source-term arrays."""

    tfwz: FloatArray
    tfTxx: FloatArray
    tfTxy: FloatArray
    tfTyy: FloatArray


def _case03_common(
    grid: Grid2D,
    t: float,
    parameters: Case03SourceTermParameters | None,
) -> dict[str, object]:
    """Collect common arrays and parameters for Case 03 source terms."""
    params = parameters or Case03SourceTermParameters()
    params.validate()

    x = grid.X
    y = grid.Y

    return {
        "p": params,
        "x": x,
        "y": y,
        "exp_at": np.exp(params.at * t),
        "exp_2at": np.exp(2.0 * params.at * t),
    }


def evaluate_case_03_tfwz(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case03SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfwz`` source term for MMS Case 03."""
    c = _case03_common(grid, t, parameters)
    p: Case03SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    betann = p.beta
    at = p.at
    a2xx, a3xx, b2xx, b3xx = p.a2xx, p.a3xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy, b1xy, b2xy, b3xy = p.a1xy, p.a2xy, p.a3xy, p.b1xy, p.b2xy, p.b3xy
    a2yy, a3yy, b2yy, b3yy = p.a2yy, p.a3yy, p.b2yy, p.b3yy

    # --- tfwz: 12 top-level terms (mechanical split) ---
    term_1 = (8 * at * (x**2 - 2 * x**3 + x**4) * (-2 + 12 * y**2)) / np.exp(at * t)
    term_2 = (32 * at * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
    term_3 = (32 * at * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
    term_4 = (
        32
        * x
        * (1 - 3 * x + 2 * x**2)
        * (-0.5 * y**2 + y**4 / 2.0)
        * (
            (192 * (x**2 - 2 * x**3 + x**4) * y) / np.exp(at * t)
            + (32 * x * (-3 + 4 * x) * (-y + 2 * y**3)) / np.exp(at * t)
            + (32 * (1 - 3 * x + 2 * x**2) * (-y + 2 * y**3)) / np.exp(at * t)
        )
    ) / np.exp(at * t)
    term_5 = (
        betann
        * (
            (192 * (x**2 - 2 * x**3 + x**4)) / np.exp(at * t)
            + (32 * x * (-3 + 4 * x) * (-1 + 6 * y**2)) / np.exp(at * t)
            + (32 * (1 - 3 * x + 2 * x**2) * (-1 + 6 * y**2)) / np.exp(at * t)
            + (8 * (2 - 12 * x + 12 * x**2) * (-2 + 12 * y**2)) / np.exp(at * t)
            + (384 * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
        )
    ) / Rey
    term_6 = (
        8
        * (x**2 - 2 * x**3 + x**4)
        * (-2 * y + 4 * y**3)
        * (
            (8 * (2 * x - 6 * x**2 + 4 * x**3) * (-2 + 12 * y**2)) / np.exp(at * t)
            + (128 * x * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
            + (64 * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
        )
    ) / np.exp(at * t)
    term_7 = (
        32
        * x
        * (1 - 3 * x + 2 * x**2)
        * (-y + 2 * y**3)
        * (
            (8 * (x**2 - 2 * x**3 + x**4) * (-2 + 12 * y**2)) / np.exp(at * t)
            + (32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
            + (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
        )
    ) / np.exp(at * t)
    term_8 = (
        8
        * (2 * x - 6 * x**2 + 4 * x**3)
        * (-2 * y + 4 * y**3)
        * (
            (8 * (x**2 - 2 * x**3 + x**4) * (-2 + 12 * y**2)) / np.exp(at * t)
            + (32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
            + (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
        )
    ) / np.exp(at * t)
    term_9 = (
        (1 - betann)
        * (-(a3xy * np.pi**2 * np.cos(np.pi * x)) - a2xy * np.pi**2 * np.sin(np.pi * x))
        * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
    ) / np.exp(at * t)
    term_10 = (
        (1 - betann)
        * (a2xx * np.pi * np.cos(np.pi * x) - a3xx * np.pi * np.sin(np.pi * x))
        * (b2xx * np.pi * np.cos(np.pi * y) - b3xx * np.pi * np.sin(np.pi * y))
    ) / np.exp(at * t)
    term_11 = (
        (1 - betann)
        * (a2yy * np.pi * np.cos(np.pi * x) - a3yy * np.pi * np.sin(np.pi * x))
        * (b2yy * np.pi * np.cos(np.pi * y) - b3yy * np.pi * np.sin(np.pi * y))
    ) / np.exp(at * t)
    term_12 = (
        (1 - betann)
        * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
        * (-(b3xy * np.pi**2 * np.cos(np.pi * y)) - b2xy * np.pi**2 * np.sin(np.pi * y))
    ) / np.exp(at * t)

    return (
        term_1 + term_2 + term_3 + term_4 + term_5 - term_6 + term_7 - term_8 - term_9 + term_10 - term_11 + term_12
    )


def evaluate_case_03_tftxx(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case03SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxx`` source term for MMS Case 03."""
    c = _case03_common(grid, t, parameters)
    p: Case03SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    xi = p.xi
    alphaG = p.alpha_g
    at = p.at
    a1xx, a2xx, a3xx = p.a1xx, p.a2xx, p.a3xx
    b1xx, b2xx, b3xx = p.b1xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy = p.a1xy, p.a2xy, p.a3xy
    b1xy, b2xy, b3xy = p.b1xy, p.b2xy, p.b3xy
    a1yy, a2yy, a3yy = p.a1yy, p.a2yy, p.a3yy
    b1yy, b2yy, b3yy = p.b1yy, p.b2yy, p.b3yy

    # --- tftxx: 4 top-level terms (mechanical split) ---
    term_1 = (-16 * (1 - betann) * (2 * x - 6 * x**2 + 4 * x**3) * (-2 * y + 4 * y**3)) / (np.exp(at * t) * Rey)
    term_2 = (
        alphaG
        * Rey
        * Wi
        * (
            (
                (1 - betann) ** 2
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x)) ** 2
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y)) ** 2
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann) ** 2
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x)) ** 2
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y)) ** 2
            )
            / np.exp(2 * at * t)
        )
    ) / (1 - betann)
    term_3 = Wi * (
        -(
            (
                at
                * (1 - betann)
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
            )
            / np.exp(at * t)
        )
        - (
            32
            * (1 - betann)
            * x
            * (1 - 3 * x + 2 * x**2)
            * (-y + 2 * y**3)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            8
            * (1 - betann)
            * (2 * x - 6 * x**2 + 4 * x**3)
            * (-2 * y + 4 * y**3)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + (
            8
            * (1 - betann)
            * (x**2 - 2 * x**3 + x**4)
            * (-2 * y + 4 * y**3)
            * (a2xx * np.pi * np.cos(np.pi * x) - a3xx * np.pi * np.sin(np.pi * x))
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            16
            * (1 - betann)
            * (x**2 - 2 * x**3 + x**4)
            * (-2 + 12 * y**2)
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            32
            * (1 - betann)
            * x
            * (1 - 3 * x + 2 * x**2)
            * (-0.5 * y**2 + y**4 / 2.0)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * (b2xx * np.pi * np.cos(np.pi * y) - b3xx * np.pi * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + xi
        * (
            (
                16
                * (1 - betann)
                * (2 * x - 6 * x**2 + 4 * x**3)
                * (-2 * y + 4 * y**3)
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                8
                * (1 - betann)
                * (x**2 - 2 * x**3 + x**4)
                * (-2 + 12 * y**2)
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann)
                * (
                    (-32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                    - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                )
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(at * t)
        )
    )
    term_4 = (
        (1 - betann)
        * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
        * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        * (
            1
            + (
                epsylon
                * Rey
                * Wi
                * (
                    (
                        (1 - betann)
                        * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                        * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
                    )
                    / np.exp(at * t)
                    + (
                        (1 - betann)
                        * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                        * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
                    )
                    / np.exp(at * t)
                )
            )
            / (1 - betann)
        )
    ) / np.exp(at * t)

    return term_1 + term_2 + term_3 + term_4


def evaluate_case_03_tftxy(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case03SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxy`` source term for MMS Case 03."""
    c = _case03_common(grid, t, parameters)
    p: Case03SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    xi = p.xi
    alphaG = p.alpha_g
    epsylon = p.epsilon
    at = p.at
    a1xx, a2xx, a3xx = p.a1xx, p.a2xx, p.a3xx
    b1xx, b2xx, b3xx = p.b1xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy = p.a1xy, p.a2xy, p.a3xy
    b1xy, b2xy, b3xy = p.b1xy, p.b2xy, p.b3xy
    a1yy, a2yy, a3yy = p.a1yy, p.a2yy, p.a3yy
    b1yy, b2yy, b3yy = p.b1yy, p.b2yy, p.b3yy

    # --- tftxy: 4 top-level terms (mechanical split) ---
    term_1 = (
        (1 - betann)
        * (
            (8 * (x**2 - 2 * x**3 + x**4) * (-2 + 12 * y**2)) / np.exp(at * t)
            - (32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
            - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
        )
    ) / Rey
    term_2 = (
        alphaG
        * Rey
        * Wi
        * (
            (
                (1 - betann) ** 2
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann) ** 2
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
                * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
        )
    ) / (1 - betann)
    term_3 = (
        (1 - betann)
        * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
        * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        * (
            1
            + (
                epsylon
                * Rey
                * Wi
                * (
                    (
                        (1 - betann)
                        * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                        * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
                    )
                    / np.exp(at * t)
                    + (
                        (1 - betann)
                        * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                        * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
                    )
                    / np.exp(at * t)
                )
            )
            / (1 - betann)
        )
    ) / np.exp(at * t)
    term_4 = Wi * (
        -(
            (
                (1 - betann)
                * (
                    (-32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                    - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                )
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
            )
            / np.exp(at * t)
        )
        - (
            at
            * (1 - betann)
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(at * t)
        + (
            8
            * (1 - betann)
            * (x**2 - 2 * x**3 + x**4)
            * (-2 * y + 4 * y**3)
            * (a2xy * np.pi * np.cos(np.pi * x) - a3xy * np.pi * np.sin(np.pi * x))
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            8
            * (1 - betann)
            * (x**2 - 2 * x**3 + x**4)
            * (-2 + 12 * y**2)
            * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
            * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            32
            * (1 - betann)
            * x
            * (1 - 3 * x + 2 * x**2)
            * (-0.5 * y**2 + y**4 / 2.0)
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b2xy * np.pi * np.cos(np.pi * y) - b3xy * np.pi * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + xi
        * (
            (
                4
                * (1 - betann)
                * (x**2 - 2 * x**3 + x**4)
                * (-2 + 12 * y**2)
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann)
                * (
                    (-32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                    - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                )
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
            )
            / (2.0 * np.exp(at * t))
            - (
                32
                * (1 - betann)
                * x
                * (1 - 3 * x + 2 * x**2)
                * (-y + 2 * y**3)
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                8
                * (1 - betann)
                * (2 * x - 6 * x**2 + 4 * x**3)
                * (-2 * y + 4 * y**3)
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                4
                * (1 - betann)
                * (x**2 - 2 * x**3 + x**4)
                * (-2 + 12 * y**2)
                * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann)
                * (
                    (-32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                    - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                )
                * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
            )
            / (2.0 * np.exp(at * t))
        )
    )

    return -term_1 + term_2 + term_3 + term_4


def evaluate_case_03_tftyy(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case03SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTyy`` source term for MMS Case 03."""
    c = _case03_common(grid, t, parameters)
    p: Case03SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    xi = p.xi
    alphaG = p.alpha_g
    epsylon = p.epsilon
    at = p.at
    a1xx, a2xx, a3xx = p.a1xx, p.a2xx, p.a3xx
    b1xx, b2xx, b3xx = p.b1xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy = p.a1xy, p.a2xy, p.a3xy
    b1xy, b2xy, b3xy = p.b1xy, p.b2xy, p.b3xy
    a1yy, a2yy, a3yy = p.a1yy, p.a2yy, p.a3yy
    b1yy, b2yy, b3yy = p.b1yy, p.b2yy, p.b3yy

    # --- tftyy: 4 top-level terms (mechanical split) ---
    term_1 = (64 * (1 - betann) * x * (1 - 3 * x + 2 * x**2) * (-y + 2 * y**3)) / (np.exp(at * t) * Rey)
    term_2 = (
        alphaG
        * Rey
        * Wi
        * (
            (
                (1 - betann) ** 2
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x)) ** 2
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y)) ** 2
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann) ** 2
                * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x)) ** 2
                * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y)) ** 2
            )
            / np.exp(2 * at * t)
        )
    ) / (1 - betann)
    term_3 = (
        (1 - betann)
        * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
        * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        * (
            1
            + (
                epsylon
                * Rey
                * Wi
                * (
                    (
                        (1 - betann)
                        * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                        * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
                    )
                    / np.exp(at * t)
                    + (
                        (1 - betann)
                        * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                        * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
                    )
                    / np.exp(at * t)
                )
            )
            / (1 - betann)
        )
    ) / np.exp(at * t)
    term_4 = Wi * (
        (
            -2
            * (1 - betann)
            * (
                (-32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
            )
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(at * t)
        - (
            at
            * (1 - betann)
            * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
            * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        )
        / np.exp(at * t)
        + (
            32
            * (1 - betann)
            * x
            * (1 - 3 * x + 2 * x**2)
            * (-y + 2 * y**3)
            * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
            * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + (
            8
            * (1 - betann)
            * (2 * x - 6 * x**2 + 4 * x**3)
            * (-2 * y + 4 * y**3)
            * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
            * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + (
            8
            * (1 - betann)
            * (x**2 - 2 * x**3 + x**4)
            * (-2 * y + 4 * y**3)
            * (a2yy * np.pi * np.cos(np.pi * x) - a3yy * np.pi * np.sin(np.pi * x))
            * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            32
            * (1 - betann)
            * x
            * (1 - 3 * x + 2 * x**2)
            * (-0.5 * y**2 + y**4 / 2.0)
            * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
            * (b2yy * np.pi * np.cos(np.pi * y) - b3yy * np.pi * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + xi
        * (
            (
                8
                * (1 - betann)
                * (x**2 - 2 * x**3 + x**4)
                * (-2 + 12 * y**2)
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann)
                * (
                    (-32 * x * (-3 + 4 * x) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                    - (32 * (1 - 3 * x + 2 * x**2) * (-0.5 * y**2 + y**4 / 2.0)) / np.exp(at * t)
                )
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(at * t)
            - (
                64
                * (1 - betann)
                * x
                * (1 - 3 * x + 2 * x**2)
                * (-y + 2 * y**3)
                * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
        )
    )

    return term_1 + term_2 + term_3 + term_4


