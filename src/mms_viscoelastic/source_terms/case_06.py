"""Source terms for MMS Case 06.

This module ports the algebraic source terms from the original Fortran
routine:

``src/fortran_original/4Order_LPOG_Euler/case_06.f::source_term_case_06(t)``

The velocity/vorticity fields follow the same Taylor-Green-vortex
trigonometric ansatz as cases 04 and 05; the polymeric stress ansatz is
the same trigonometric form as case 03 (and case 12).

Every term below -- including the comparatively compact ``tfwz`` -- was
generated by the Fortran-to-Python mechanical script and copied verbatim,
per the discipline established after the Case 04 sign error.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import NDArray

from mms_viscoelastic.grids import Grid2D

FloatArray = NDArray[np.float64]

CASE06_FORTRAN_ARRAYS: tuple[str, ...] = ("tfwz", "tfTxx", "tfTxy", "tfTyy")


@dataclass(frozen=True)
class Case06SourceTermParameters:
    """Physical and constitutive parameters required by Case 06 source terms."""

    reynolds: float = 1.0
    wi: float = 1.0
    beta: float = 0.5
    epsilon: float = 0.0
    xi: float = 0.0
    alpha_g: float = 0.0
    at: float = 0.0

    a1xx: float = 1.0
    a2xx: float = 1.0
    a3xx: float = 1.0
    b1xx: float = 1.0
    b2xx: float = 1.0
    b3xx: float = 1.0

    a1xy: float = 1.0
    a2xy: float = 1.0
    a3xy: float = 1.0
    b1xy: float = 1.0
    b2xy: float = 1.0
    b3xy: float = 1.0

    a1yy: float = 1.0
    a2yy: float = 1.0
    a3yy: float = 1.0
    b1yy: float = 1.0
    b2yy: float = 1.0
    b3yy: float = 1.0

    def validate(self) -> None:
        """Validate parameters needed by the ported source terms."""
        if self.reynolds == 0.0:
            raise ValueError("reynolds must be nonzero.")
        if self.wi == 0.0:
            raise ValueError("wi must be nonzero.")
        if not np.isfinite(self.beta):
            raise ValueError("beta must be finite.")


@dataclass(frozen=True)
class Case06SourceTerms:
    """Container for MMS Case 06 source-term arrays."""

    tfwz: FloatArray
    tfTxx: FloatArray
    tfTxy: FloatArray
    tfTyy: FloatArray


def _case06_common(
    grid: Grid2D,
    t: float,
    parameters: Case06SourceTermParameters | None,
) -> dict[str, object]:
    """Collect common arrays and parameters for Case 06 source terms."""
    params = parameters or Case06SourceTermParameters()
    params.validate()

    return {
        "p": params,
        "x": grid.X,
        "y": grid.Y,
    }


def evaluate_case_06_tfwz(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case06SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfwz`` source term for MMS Case 06."""
    c = _case06_common(grid, t, parameters)
    p: Case06SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    betann = p.beta
    at = p.at
    a2xx, a3xx, b2xx, b3xx = p.a2xx, p.a3xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy, b1xy, b2xy, b3xy = p.a1xy, p.a2xy, p.a3xy, p.b1xy, p.b2xy, p.b3xy
    a2yy, a3yy, b2yy, b3yy = p.a2yy, p.a3yy, p.b2yy, p.b3yy

    # --- tfwz: 6 top-level terms (mechanical split) ---
    term_1 = (16 * at * np.pi * np.cos(np.pi * x) * np.cos(np.pi * y)) / np.exp(at * t)
    term_2 = (32 * betann * np.pi**3 * np.cos(np.pi * x) * np.cos(np.pi * y)) / (np.exp(at * t) * Rey)
    term_3 = (
        (1 - betann)
        * (-(a3xy * np.pi**2 * np.cos(np.pi * x)) - a2xy * np.pi**2 * np.sin(np.pi * x))
        * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
    ) / np.exp(at * t)
    term_4 = (
        (1 - betann)
        * (a2xx * np.pi * np.cos(np.pi * x) - a3xx * np.pi * np.sin(np.pi * x))
        * (b2xx * np.pi * np.cos(np.pi * y) - b3xx * np.pi * np.sin(np.pi * y))
    ) / np.exp(at * t)
    term_5 = (
        (1 - betann)
        * (a2yy * np.pi * np.cos(np.pi * x) - a3yy * np.pi * np.sin(np.pi * x))
        * (b2yy * np.pi * np.cos(np.pi * y) - b3yy * np.pi * np.sin(np.pi * y))
    ) / np.exp(at * t)
    term_6 = (
        (1 - betann)
        * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
        * (-(b3xy * np.pi**2 * np.cos(np.pi * y)) - b2xy * np.pi**2 * np.sin(np.pi * y))
    ) / np.exp(at * t)

    return term_1 - term_2 - term_3 + term_4 - term_5 + term_6


def evaluate_case_06_tftxx(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case06SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxx`` source term for MMS Case 06."""
    c = _case06_common(grid, t, parameters)
    p: Case06SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    xi = p.xi
    alphaG = p.alpha_g
    at = p.at
    a1xx, a2xx, a3xx = p.a1xx, p.a2xx, p.a3xx
    b1xx, b2xx, b3xx = p.b1xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy = p.a1xy, p.a2xy, p.a3xy
    b1xy, b2xy, b3xy = p.b1xy, p.b2xy, p.b3xy
    a1yy, a2yy, a3yy = p.a1yy, p.a2yy, p.a3yy
    b1yy, b2yy, b3yy = p.b1yy, p.b2yy, p.b3yy

    # --- tftxx: 4 top-level terms (mechanical split) ---
    term_1 = (16 * (1 - betann) * np.pi * np.sin(np.pi * x) * np.sin(np.pi * y)) / (np.exp(at * t) * Rey)
    term_2 = (
        alphaG
        * Rey
        * Wi
        * (
            ((1 - betann) ** 2 * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x)) ** 2
             * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y)) ** 2)
            / np.exp(2 * at * t)
            + ((1 - betann) ** 2 * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x)) ** 2
               * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y)) ** 2)
            / np.exp(2 * at * t)
        )
    ) / (1 - betann)
    term_3 = Wi * (
        -(
            (at * (1 - betann) * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
             * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y)))
            / np.exp(at * t)
        )
        + (
            16
            * (1 - betann)
            * np.pi
            * np.sin(np.pi * x)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * np.sin(np.pi * y)
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            16
            * (1 - betann)
            * np.pi
            * xi
            * np.sin(np.pi * x)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * np.sin(np.pi * y)
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        + (
            8
            * (1 - betann)
            * np.cos(np.pi * x)
            * (a2xx * np.pi * np.cos(np.pi * x) - a3xx * np.pi * np.sin(np.pi * x))
            * np.sin(np.pi * y)
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            16
            * (1 - betann)
            * np.pi
            * np.cos(np.pi * x)
            * np.cos(np.pi * y)
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            8
            * (1 - betann)
            * np.cos(np.pi * y)
            * np.sin(np.pi * x)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * (b2xx * np.pi * np.cos(np.pi * y) - b3xx * np.pi * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
    )
    term_4 = (
        (1 - betann)
        * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
        * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        * (
            1
            + (
                epsylon
                * Rey
                * Wi
                * (
                    ((1 - betann) * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                     * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y)))
                    / np.exp(at * t)
                    + ((1 - betann) * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                       * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y)))
                    / np.exp(at * t)
                )
            )
            / (1 - betann)
        )
    ) / np.exp(at * t)

    return term_1 + term_2 + term_3 + term_4


def evaluate_case_06_tftxy(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case06SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxy`` source term for MMS Case 06."""
    c = _case06_common(grid, t, parameters)
    p: Case06SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    alphaG = p.alpha_g
    at = p.at
    a1xx, a2xx, a3xx = p.a1xx, p.a2xx, p.a3xx
    b1xx, b2xx, b3xx = p.b1xx, p.b2xx, p.b3xx
    a1xy, a2xy, a3xy = p.a1xy, p.a2xy, p.a3xy
    b1xy, b2xy, b3xy = p.b1xy, p.b2xy, p.b3xy
    a1yy, a2yy, a3yy = p.a1yy, p.a2yy, p.a3yy
    b1yy, b2yy, b3yy = p.b1yy, p.b2yy, p.b3yy

    # --- tftxy: 3 top-level terms (mechanical split) ---
    term_1 = (
        alphaG
        * Rey
        * Wi
        * (
            (
                (1 - betann) ** 2
                * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann) ** 2
                * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
                * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
                * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
            )
            / np.exp(2 * at * t)
        )
    ) / (1 - betann)
    term_2 = Wi * (
        (
            8
            * (1 - betann)
            * np.pi
            * np.cos(np.pi * x)
            * np.cos(np.pi * y)
            * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
            * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            at
            * (1 - betann)
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(at * t)
        + (
            8
            * (1 - betann)
            * np.cos(np.pi * x)
            * (a2xy * np.pi * np.cos(np.pi * x) - a3xy * np.pi * np.sin(np.pi * x))
            * np.sin(np.pi * y)
            * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            8
            * (1 - betann)
            * np.pi
            * np.cos(np.pi * x)
            * np.cos(np.pi * y)
            * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
            * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
        - (
            8
            * (1 - betann)
            * np.cos(np.pi * y)
            * np.sin(np.pi * x)
            * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
            * (b2xy * np.pi * np.cos(np.pi * y) - b3xy * np.pi * np.sin(np.pi * y))
        )
        / np.exp(2 * at * t)
    )
    term_3 = (
        (1 - betann)
        * (a1xy + a3xy * np.cos(np.pi * x) + a2xy * np.sin(np.pi * x))
        * (b1xy + b3xy * np.cos(np.pi * y) + b2xy * np.sin(np.pi * y))
        * (
            1
            + (
                epsylon
                * Rey
                * Wi
                * (
                    ((1 - betann) * (a1xx + a3xx * np.cos(np.pi * x) + a2xx * np.sin(np.pi * x))
                     * (b1xx + b3xx * np.cos(np.pi * y) + b2xx * np.sin(np.pi * y)))
                    / np.exp(at * t)
                    + ((1 - betann) * (a1yy + a3yy * np.cos(np.pi * x) + a2yy * np.sin(np.pi * x))
                       * (b1yy + b3yy * np.cos(np.pi * y) + b2yy * np.sin(np.pi * y)))
                    / np.exp(at * t)
                )
            )
            / (1 - betann)
        )
    ) / np.exp(at * t)

    return term_1 + term_2 + term_3


