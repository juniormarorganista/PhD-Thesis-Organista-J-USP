"""Source terms for MMS Case 08.

This module ports the algebraic source terms from the original Fortran
routine:

``src/fortran_original/4Order_LPOG_Euler/case_08.f::source_term_case_08(t)``

This is one of the largest and densest ported cases: the velocity and
vorticity fields follow a purely polynomial spatial structure (decaying
in time through a hyperbolic tangent, like case 07), and the manufactured
solution's own nonlinear convective term (``J(wz, psi)``-like products of
the velocity/vorticity fields and their derivatives) is written out
explicitly in the source terms rather than vanishing, making every
expression here substantially larger than cases 01-07 (``tfTxy`` alone
spans 212 matched parenthesis pairs). The polymeric stress ansatz is the
same quadratic-polynomial form as case 02.

Every term below -- without exception, regardless of size -- was
generated by the Fortran-to-Python mechanical script and copied
verbatim, then reformatted only by ``ruff format`` (whitespace/line-
wrapping only, never semantics), per the discipline established after
the Case 04 sign error.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import NDArray

from mms_viscoelastic.grids import Grid2D

FloatArray = NDArray[np.float64]

CASE08_FORTRAN_ARRAYS: tuple[str, ...] = ("tfwz", "tfTxx", "tfTxy", "tfTyy")


@dataclass(frozen=True)
class Case08SourceTermParameters:
    """Physical and constitutive parameters required by Case 08 source terms."""

    reynolds: float = 1.0
    wi: float = 1.0
    beta: float = 0.5
    epsilon: float = 0.0
    xi: float = 0.0
    alpha_g: float = 0.0
    at: float = 0.0

    a1xx: float = 1.0
    a2xx: float = 1.0
    a3xx: float = 1.0
    b1xx: float = 1.0
    b2xx: float = 1.0
    b3xx: float = 1.0

    a1xy: float = 1.0
    a2xy: float = 1.0
    a3xy: float = 1.0
    b1xy: float = 1.0
    b2xy: float = 1.0
    b3xy: float = 1.0

    a1yy: float = 1.0
    a2yy: float = 1.0
    a3yy: float = 1.0
    b1yy: float = 1.0
    b2yy: float = 1.0
    b3yy: float = 1.0

    def validate(self) -> None:
        """Validate parameters needed by the ported source terms."""
        if self.reynolds == 0.0:
            raise ValueError("reynolds must be nonzero.")
        if self.wi == 0.0:
            raise ValueError("wi must be nonzero.")
        if not np.isfinite(self.beta):
            raise ValueError("beta must be finite.")


@dataclass(frozen=True)
class Case08SourceTerms:
    """Container for MMS Case 08 source-term arrays."""

    tfwz: FloatArray
    tfTxx: FloatArray
    tfTxy: FloatArray
    tfTyy: FloatArray


def _case08_common(
    grid: Grid2D,
    t: float,
    parameters: Case08SourceTermParameters | None,
) -> dict[str, object]:
    """Collect common arrays and parameters for Case 08 source terms."""
    params = parameters or Case08SourceTermParameters()
    params.validate()

    return {
        "p": params,
        "x": grid.X,
        "y": grid.Y,
    }


def evaluate_case_08_tfwz(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case08SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfwz`` source term for MMS Case 08."""
    c = _case08_common(grid, t, parameters)
    p: Case08SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    betann = p.beta
    at = p.at
    a2xx = p.a2xx
    a3xx = p.a3xx
    b2xx = p.b2xx
    b3xx = p.b3xx
    a1xy = p.a1xy
    a2xy = p.a2xy
    a3xy = p.a3xy
    b1xy = p.b1xy
    b2xy = p.b2xy
    b3xy = p.b3xy
    a2yy = p.a2yy
    a3yy = p.a3yy
    b2yy = p.b2yy
    b3yy = p.b3yy

    # --- tfwz: 14 top-level terms (mechanical split) ---
    term_1 = (2 * b3xy * (1 - betann) * (a1xy + a2xy * x + a3xy * x**2)) / np.exp(
        at * t
    )
    term_2 = ((1 - betann) * (a2xx + 2 * a3xx * x) * (b2xx + 2 * b3xx * y)) / np.exp(
        at * t
    )
    term_3 = ((1 - betann) * (a2yy + 2 * a3yy * x) * (b2yy + 2 * b3yy * y)) / np.exp(
        at * t
    )
    term_4 = (2 * a3xy * (1 - betann) * (b1xy + b2xy * y + b3xy * y**2)) / np.exp(
        at * t
    )
    term_5 = 128 * at * (1 - x) ** 2 * x**2 * y * (1.0e0 / np.cosh(4 - 8 * at * t)) ** 2
    term_6 = (
        128 * at * (1 - x) ** 2 * y**3 * (1.0e0 / np.cosh(4 - 8 * at * t)) ** 2
    ) / 3.0
    term_7 = (
        512 * at * (1 - x) * x * y**3 * (1.0e0 / np.cosh(4 - 8 * at * t)) ** 2
    ) / 3.0
    term_8 = (128 * at * x**2 * y**3 * (1.0e0 / np.cosh(4 - 8 * at * t)) ** 2) / 3.0
    term_9 = (
        betann
        * (
            32 * (1 - x) ** 2 * y * (1 - np.tanh(4 - 8 * at * t))
            - 128 * (1 - x) * x * y * (1 - np.tanh(4 - 8 * at * t))
            + 32 * x**2 * y * (1 - np.tanh(4 - 8 * at * t))
            + (32 * (1 - x) ** 2 - 128 * (1 - x) * x + 32 * x**2)
            * y
            * (1 - np.tanh(4 - 8 * at * t))
            + 64 * y**3 * (1 - np.tanh(4 - 8 * at * t))
        )
    ) / Rey
    term_10 = (
        -16 * (1 - x) ** 2 * x * y**2 * (1 - np.tanh(4 - 8 * at * t))
        + 16 * (1 - x) * x**2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
    ) * (
        16 * (1 - x) ** 2 * x**2 * y * (1 - np.tanh(4 - 8 * at * t))
        + (16 * (1 - x) ** 2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
        - (64 * (1 - x) * x * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
        + (16 * x**2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
    )
    term_11 = (
        16 * (1 - x) ** 2 * x**2 * (1 - np.tanh(4 - 8 * at * t))
        + 16 * (1 - x) ** 2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
        - 64 * (1 - x) * x * y**2 * (1 - np.tanh(4 - 8 * at * t))
        + 16 * x**2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
    ) * (
        (-16 * (1 - x) ** 2 * x * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
        + (16 * (1 - x) * x**2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
    )
    term_12 = (
        8
        * (1 - x) ** 2
        * x**2
        * y**2
        * (
            32 * (1 - x) ** 2 * x * y * (1 - np.tanh(4 - 8 * at * t))
            - 32 * (1 - x) * x**2 * y * (1 - np.tanh(4 - 8 * at * t))
            - 32 * (1 - x) * y**3 * (1 - np.tanh(4 - 8 * at * t))
            + 32 * x * y**3 * (1 - np.tanh(4 - 8 * at * t))
        )
        * (1 - np.tanh(4 - 8 * at * t))
    )
    term_13 = (
        16
        * (1 - x) ** 2
        * x
        * y**2
        * (
            16 * (1 - x) ** 2 * x**2 * y * (1 - np.tanh(4 - 8 * at * t))
            + (16 * (1 - x) ** 2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
            - (64 * (1 - x) * x * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
            + (16 * x**2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
        )
        * (1 - np.tanh(4 - 8 * at * t))
    )
    term_14 = (
        16
        * (1 - x)
        * x**2
        * y**2
        * (
            16 * (1 - x) ** 2 * x**2 * y * (1 - np.tanh(4 - 8 * at * t))
            + (16 * (1 - x) ** 2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
            - (64 * (1 - x) * x * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
            + (16 * x**2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
        )
        * (1 - np.tanh(4 - 8 * at * t))
    )

    return (
        term_1
        + term_2
        - term_3
        - term_4
        - term_5
        - term_6
        + term_7
        - term_8
        + term_9
        - term_10
        - term_11
        - term_12
        - term_13
        + term_14
    )


def evaluate_case_08_tftxx(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case08SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxx`` source term for MMS Case 08."""
    c = _case08_common(grid, t, parameters)
    p: Case08SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    xi = p.xi
    alphaG = p.alpha_g
    at = p.at
    a1xx = p.a1xx
    a2xx = p.a2xx
    a3xx = p.a3xx
    b1xx = p.b1xx
    b2xx = p.b2xx
    b3xx = p.b3xx
    a1xy = p.a1xy
    a2xy = p.a2xy
    a3xy = p.a3xy
    b1xy = p.b1xy
    b2xy = p.b2xy
    b3xy = p.b3xy
    a1yy = p.a1yy
    a2yy = p.a2yy
    a3yy = p.a3yy
    b1yy = p.b1yy
    b2yy = p.b2yy
    b3yy = p.b3yy

    # --- tftxx: 4 top-level terms (mechanical split) ---
    term_1 = (
        alphaG
        * Rey
        * Wi
        * (
            (
                (1 - betann) ** 2
                * (a1xx + a2xx * x + a3xx * x**2) ** 2
                * (b1xx + b2xx * y + b3xx * y**2) ** 2
            )
            / np.exp(2 * at * t)
            + (
                (1 - betann) ** 2
                * (a1xy + a2xy * x + a3xy * x**2) ** 2
                * (b1xy + b2xy * y + b3xy * y**2) ** 2
            )
            / np.exp(2 * at * t)
        )
    ) / (1 - betann)
    term_2 = (
        (1 - betann)
        * (a1xx + a2xx * x + a3xx * x**2)
        * (b1xx + b2xx * y + b3xx * y**2)
        * (
            1
            + (
                epsylon
                * Rey
                * Wi
                * (
                    (
                        (1 - betann)
                        * (a1xx + a2xx * x + a3xx * x**2)
                        * (b1xx + b2xx * y + b3xx * y**2)
                    )
                    / np.exp(at * t)
                    + (
                        (1 - betann)
                        * (a1yy + a2yy * x + a3yy * x**2)
                        * (b1yy + b2yy * y + b3yy * y**2)
                    )
                    / np.exp(at * t)
                )
            )
            / (1 - betann)
        )
    ) / np.exp(at * t)
    term_3 = (
        2
        * (1 - betann)
        * (
            16 * (1 - x) ** 2 * x * y**2 * (1 - np.tanh(4 - 8 * at * t))
            - 16 * (1 - x) * x**2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
        )
    ) / Rey
    term_4 = Wi * (
        -(
            (
                at
                * (1 - betann)
                * (a1xx + a2xx * x + a3xx * x**2)
                * (b1xx + b2xx * y + b3xx * y**2)
            )
            / np.exp(at * t)
        )
        - (
            2
            * (1 - betann)
            * (a1xx + a2xx * x + a3xx * x**2)
            * (b1xx + b2xx * y + b3xx * y**2)
            * (
                16 * (1 - x) ** 2 * x * y**2 * (1 - np.tanh(4 - 8 * at * t))
                - 16 * (1 - x) * x**2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
            )
        )
        / np.exp(at * t)
        + (
            (1 - betann)
            * (a1xx + a2xx * x + a3xx * x**2)
            * (b1xx + b2xx * y + b3xx * y**2)
            * (
                -16 * (1 - x) ** 2 * x * y**2 * (1 - np.tanh(4 - 8 * at * t))
                + 16 * (1 - x) * x**2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
            )
        )
        / np.exp(at * t)
        + (
            (1 - betann)
            * (a1xx + a2xx * x + a3xx * x**2)
            * (b2xx + 2 * b3xx * y)
            * (
                (-16 * (1 - x) ** 2 * x * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
                + (16 * (1 - x) * x**2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
            )
        )
        / np.exp(at * t)
        + xi
        * (
            (
                2
                * (1 - betann)
                * (a1xx + a2xx * x + a3xx * x**2)
                * (b1xx + b2xx * y + b3xx * y**2)
                * (
                    16 * (1 - x) ** 2 * x * y**2 * (1 - np.tanh(4 - 8 * at * t))
                    - 16 * (1 - x) * x**2 * y**2 * (1 - np.tanh(4 - 8 * at * t))
                )
            )
            / np.exp(at * t)
            + (
                (1 - betann)
                * (a1xy + a2xy * x + a3xy * x**2)
                * (b1xy + b2xy * y + b3xy * y**2)
                * (
                    (-16 * (1 - x) ** 2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
                    + (64 * (1 - x) * x * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
                    - (16 * x**2 * y**3 * (1 - np.tanh(4 - 8 * at * t))) / 3.0
                )
            )
            / np.exp(at * t)
            + (
                16
                * (1 - betann)
                * (1 - x) ** 2
                * x**2
                * (a1xy + a2xy * x + a3xy * x**2)
                * y
                * (b1xy + b2xy * y + b3xy * y**2)
                * (1 - np.tanh(4 - 8 * at * t))
            )
            / np.exp(at * t)
        )
        + (
            8
            * (1 - betann)
            * (1 - x) ** 2
            * x**2
            * (a2xx + 2 * a3xx * x)
            * y**2
            * (b1xx + b2xx * y + b3xx * y**2)
            * (1 - np.tanh(4 - 8 * at * t))
        )
        / np.exp(at * t)
        + (
            16
            * (1 - betann)
            * (1 - x) ** 2
            * x
            * (a1xx + a2xx * x + a3xx * x**2)
            * y**2
            * (b1xx + b2xx * y + b3xx * y**2)
            * (1 - np.tanh(4 - 8 * at * t))
        )
        / np.exp(at * t)
        - (
            16
            * (1 - betann)
            * (1 - x)
            * x**2
            * (a1xx + a2xx * x + a3xx * x**2)
            * y**2
            * (b1xx + b2xx * y + b3xx * y**2)
            * (1 - np.tanh(4 - 8 * at * t))
        )
        / np.exp(at * t)
        - (
            32
            * (1 - betann)
            * (1 - x) ** 2
            * x**2
            * (a1xy + a2xy * x + a3xy * x**2)
            * y
            * (b1xy + b2xy * y + b3xy * y**2)
            * (1 - np.tanh(4 - 8 * at * t))
        )
        / np.exp(at * t)
    )

    return term_1 + term_2 - term_3 + term_4


