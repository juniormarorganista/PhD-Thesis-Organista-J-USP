"""Source terms for MMS Case 10.

This module ports the algebraic source terms from the original Fortran
routine:

``src/fortran_original/4Order_LPOG_Euler/case_10.f::source_term_case_10(t)``

The velocity/vorticity fields follow the same trigonometric-times-
polynomial ansatz as case 12; the polymeric stress targets ``c1``,
``c2``, ``c3`` are the same spatially uniform constants used by case 01.

Every term below was generated by the Fortran-to-Python mechanical
script and copied verbatim, then reformatted only by ``ruff format``
(whitespace/line-wrapping only, never semantics).
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import NDArray

from mms_viscoelastic.grids import Grid2D

FloatArray = NDArray[np.float64]

CASE10_FORTRAN_ARRAYS: tuple[str, ...] = ("tfwz", "tfTxx", "tfTxy", "tfTyy")


@dataclass(frozen=True)
class Case10SourceTermParameters:
    """Physical and constitutive parameters required by Case 10 source terms."""

    reynolds: float = 1.0
    wi: float = 1.0
    beta: float = 0.5
    epsilon: float = 0.0
    xi: float = 0.0
    alpha_g: float = 0.0
    at: float = 0.0
    c1: float = 1.0
    c2: float = 2.0
    c3: float = 3.0

    def validate(self) -> None:
        """Validate parameters needed by the ported source terms."""
        if self.reynolds == 0.0:
            raise ValueError("reynolds must be nonzero.")
        if self.wi == 0.0:
            raise ValueError("wi must be nonzero.")
        if not np.isfinite(self.beta):
            raise ValueError("beta must be finite.")


@dataclass(frozen=True)
class Case10SourceTerms:
    """Container for MMS Case 10 source-term arrays."""

    tfwz: FloatArray
    tfTxx: FloatArray
    tfTxy: FloatArray
    tfTyy: FloatArray


def _case10_common(
    grid: Grid2D,
    t: float,
    parameters: Case10SourceTermParameters | None,
) -> dict[str, object]:
    """Collect common arrays and parameters for Case 10 source terms."""
    params = parameters or Case10SourceTermParameters()
    params.validate()

    return {
        "p": params,
        "x": grid.X,
        "y": grid.Y,
    }


def evaluate_case_10_tfwz(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case10SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfwz`` source term for MMS Case 10."""
    c = _case10_common(grid, t, parameters)
    p: Case10SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    betann = p.beta
    at = p.at

    # --- tfwz: 1 top-level terms (mechanical split) ---
    term_1 = (
        2
        * np.pi**2
        * Rey
        * (-1 + x)
        * x
        * (-1 + 2 * x)
        * y
        * np.cos(np.pi * x) ** 2
        * np.sin(np.pi * y)
        * (np.pi * y * np.cos(np.pi * y) + np.sin(np.pi * y))
        + 2
        * np.pi
        * np.cos(np.pi * x)
        * (
            np.pi**2
            * Rey
            * x**2
            * y
            * (-1 + x - x**2 + x * np.cos(2 * np.pi * y))
            * np.sin(np.pi * x)
            - np.exp(at * t)
            * (-1 + 2 * x)
            * (
                -4 * betann * np.pi * np.cos(np.pi * y)
                + (4 * betann * np.pi**2 - at * Rey) * y * np.sin(np.pi * y)
            )
        )
        + np.sin(np.pi * x)
        * (
            2
            * np.exp(at * t)
            * (
                np.pi
                * (at * Rey * (-1 + x) * x + betann * (4 - 4 * np.pi**2 * (-1 + x) * x))
                * np.cos(np.pi * y)
                + (
                    at * Rey
                    + np.pi**2
                    * (
                        -(at * Rey * (-1 + x) * x)
                        + 2 * betann * (-4 + np.pi**2 * (-1 + x) * x)
                    )
                )
                * y
                * np.sin(np.pi * y)
            )
            + np.pi
            * Rey
            * np.cos(np.pi * x)
            * (
                2
                * (1 + 2 * x * (-1 + x + np.pi**2 * x**2))
                * y
                * np.sin(np.pi * y) ** 2
                - np.pi
                * ((-1 + x) ** 2 * x**2 + (-1 - 2 * (-1 + x) * x) * y**2)
                * np.sin(2 * np.pi * y)
            )
            + Rey
            * (-1 + 2 * x)
            * np.sin(np.pi * x)
            * (
                y
                - np.pi**2 * (-1 + x) * x * y
                + (-1 - np.pi**2 * (-1 + x) * x) * y * np.cos(2 * np.pi * y)
                + np.pi
                * (y**2 + (-1 + x) * x * (-1 + np.pi**2 * y**2))
                * np.sin(2 * np.pi * y)
            )
        )
    ) / (np.exp(2 * at * t) * Rey)

    return term_1


def evaluate_case_10_tftxx(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case10SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxx`` source term for MMS Case 10."""
    c = _case10_common(grid, t, parameters)
    p: Case10SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    xi = p.xi
    alphaG = p.alpha_g
    at = p.at
    c1 = p.c1
    c2 = p.c2
    c3 = p.c3

    # --- tftxx: 1 top-level terms (mechanical split) ---
    term_1 = (
        (-1 + betann)
        * (
            Rey
            * (
                -((alphaG * (c1**2 + c2**2) + c1 * (c1 + c3) * epsylon) * Rey * Wi)
                + c1 * np.exp(at * t) * (-1 + at * Wi)
            )
            + 2
            * np.pi
            * np.cos(np.pi * x)
            * (
                np.pi
                * (-1 + x)
                * x
                * (np.exp(at * t) - c1 * Rey * Wi * (-1 + xi))
                * y
                * np.cos(np.pi * y)
                + (
                    np.exp(at * t) * (-1 + x) * x
                    + Rey
                    * Wi
                    * (-(c1 * (-1 + x) * x * (-1 + xi)) + c2 * (-1 + 2 * x) * xi * y)
                )
                * np.sin(np.pi * y)
            )
            + 2
            * np.sin(np.pi * x)
            * (
                np.pi
                * (
                    -(c2 * Rey * Wi * (-1 + x) * x * (-2 + xi))
                    + (-1 + 2 * x) * (np.exp(at * t) - c1 * Rey * Wi * (-1 + xi)) * y
                )
                * np.cos(np.pi * y)
                + (
                    np.exp(at * t) * (-1 + 2 * x)
                    + Rey
                    * Wi
                    * (
                        -(c1 * (-1 + 2 * x) * (-1 + xi))
                        + c2 * (-(np.pi**2 * (-1 + x) * x) + xi) * y
                    )
                )
                * np.sin(np.pi * y)
            )
        )
    ) / (np.exp(2 * at * t) * Rey)

    return term_1


def evaluate_case_10_tftxy(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case10SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTxy`` source term for MMS Case 10."""
    c = _case10_common(grid, t, parameters)
    p: Case10SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    xi = p.xi
    alphaG = p.alpha_g
    at = p.at
    c1 = p.c1
    c2 = p.c2
    c3 = p.c3

    # --- tftxy: 1 top-level terms (mechanical split) ---
    term_1 = (
        (-1 + betann)
        * (
            c2
            * Rey
            * (
                -((c1 + c3) * (alphaG + epsylon) * Rey * Wi)
                + np.exp(at * t) * (-1 + at * Wi)
            )
            + np.pi
            * (-1 + x)
            * x
            * (2 * np.exp(at * t) + Rey * Wi * (2 * c3 - (c1 + c3) * xi))
            * np.cos(np.pi * y)
            * np.sin(np.pi * x)
            + y
            * (
                -(
                    np.pi
                    * (-1 + 2 * x)
                    * (2 * np.exp(at * t) + Rey * Wi * (2 * c1 - (c1 + c3) * xi))
                    * np.cos(np.pi * x)
                )
                + (
                    -2 * np.exp(at * t)
                    + Rey
                    * Wi
                    * (
                        c3 * (-(np.pi**2 * (-1 + x) * x) + xi)
                        + c1 * (-2 + np.pi**2 * (-1 + x) * x + xi)
                    )
                )
                * np.sin(np.pi * x)
            )
            * np.sin(np.pi * y)
        )
    ) / (np.exp(2 * at * t) * Rey)

    return term_1


def evaluate_case_10_tftyy(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case10SourceTermParameters | None = None,
) -> FloatArray:
    """Evaluate the ported ``tfTyy`` source term for MMS Case 10."""
    c = _case10_common(grid, t, parameters)
    p: Case10SourceTermParameters = c["p"]  # type: ignore[assignment]
    x: FloatArray = c["x"]  # type: ignore[assignment]
    y: FloatArray = c["y"]  # type: ignore[assignment]

    Rey = p.reynolds
    Wi = p.wi
    betann = p.beta
    epsylon = p.epsilon
    xi = p.xi
    alphaG = p.alpha_g
    at = p.at
    c1 = p.c1
    c2 = p.c2
    c3 = p.c3

    # --- tftyy: 1 top-level terms (mechanical split) ---
    term_1 = (
        (-1 + betann)
        * (
            Rey
            * (
                -((alphaG * (c2**2 + c3**2) + c3 * (c1 + c3) * epsylon) * Rey * Wi)
                + c3 * np.exp(at * t) * (-1 + at * Wi)
            )
            + 2
            * np.pi
            * np.cos(np.pi * x)
            * (
                -(
                    np.pi
                    * (-1 + x)
                    * x
                    * (np.exp(at * t) - c3 * Rey * Wi * (-1 + xi))
                    * y
                    * np.cos(np.pi * y)
                )
                + (
                    -(np.exp(at * t) * (-1 + x) * x)
                    + Rey
                    * Wi
                    * (
                        c3 * (-1 + x) * x * (-1 + xi)
                        + c2 * (-1 + 2 * x) * (-2 + xi) * y
                    )
                )
                * np.sin(np.pi * y)
            )
            + 2
            * np.sin(np.pi * x)
            * (
                np.pi
                * (
                    -(c2 * Rey * Wi * (-1 + x) * x * xi)
                    - (-1 + 2 * x) * (np.exp(at * t) - c3 * Rey * Wi * (-1 + xi)) * y
                )
                * np.cos(np.pi * y)
                + (
                    np.exp(at * t) * (1 - 2 * x)
                    + Rey
                    * Wi
                    * (
                        c3 * (-1 + 2 * x) * (-1 + xi)
                        + c2 * (-2 + np.pi**2 * (-1 + x) * x + xi) * y
                    )
                )
                * np.sin(np.pi * y)
            )
        )
    ) / (np.exp(2 * at * t) * Rey)

    return term_1


def evaluate_case_10_source_terms(
    grid: Grid2D,
    t: float = 0.0,
    parameters: Case10SourceTermParameters | None = None,
) -> Case10SourceTerms:
    """Evaluate all Case 10 source terms."""
    return Case10SourceTerms(
        tfwz=evaluate_case_10_tfwz(grid, t=t, parameters=parameters),
        tfTxx=evaluate_case_10_tftxx(grid, t=t, parameters=parameters),
        tfTxy=evaluate_case_10_tftxy(grid, t=t, parameters=parameters),
        tfTyy=evaluate_case_10_tftyy(grid, t=t, parameters=parameters),
    )


