"""Reference-data comparison utilities for the Case 12 exact fields.

This module compares the Python manufactured-solution fields
(``evaluate_case_12_exact``) against CSV files generated from an isolated
Fortran reference program that ports ``exact_solutions_case_12(t)``.

Scope
-----
The comparison covers the **t=0 initial-instant** exact fields ``u``, ``v``,
``wz``, ``psi``, ``txx``, ``txy`` and ``tyy``. It does not reproduce the
time-marching solver loop (``source_term_case_12`` and the discretized PDE
update). See ``docs/case-12-solver-comparison.md`` for the full scope
statement.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from mms_viscoelastic.grids import Grid2D
from mms_viscoelastic.manufactured_solutions import Case12Parameters, evaluate_case_12_exact
from mms_viscoelastic.models.log_conformation import (
    log_conformation_to_stress,
    stress_to_log_conformation,
)
from mms_viscoelastic.numerics import (
    EulerStepParameters,
    TimeMarchingState,
    case12_multistep_march,
    case12_time_step,
    euler_step_stress,
    euler_step_wz,
)
from mms_viscoelastic.numerics.time_stepping_log import euler_step_log_conformation
from mms_viscoelastic.source_terms import Case12SourceTermParameters, evaluate_case_12_source_terms
from mms_viscoelastic.validation.source_term_reference import (
    SourceTermReferenceComparison,
    compare_case12_reference_csv,
)

CASE12_FIELD_COMPONENTS: tuple[str, ...] = ("u", "v", "wz", "psi", "txx", "txy", "tyy")
CASE12_EULER_STEP_COMPONENTS: tuple[str, ...] = ("wz", "txx", "txy", "tyy")
CASE12_TIME_STEP_COMPONENTS: tuple[str, ...] = ("wz", "txx", "txy", "tyy", "psi", "u", "v")
CASE12_LOG_EULER_STEP_COMPONENTS: tuple[str, ...] = ("wz", "txx", "txy", "tyy")


def _require_array(value: np.ndarray | None, name: str) -> np.ndarray:
    """Return ``value``, raising ``ValueError`` if it was not computed."""

    if value is None:
        raise ValueError(f"Field or source-term component {name!r} was not computed.")
    return value


def compare_case12_field_reference(
    path: str | Path,
    *,
    component: str,
    t: float = 0.0,
    parameters: Case12Parameters | None = None,
    atol: float = 1.0e-10,
    rtol: float = 1.0e-10,
) -> SourceTermReferenceComparison:
    """Compare a Python Case 12 exact field against a Fortran-generated CSV.

    Parameters
    ----------
    path:
        Reference CSV with columns ``x,y,u,v,wz,psi,txx,txy,tyy``.
    component:
        Field component to compare. Must be one of ``CASE12_FIELD_COMPONENTS``.
    t:
        Physical time. The reference program defaults to ``t=0``.
    parameters:
        Case-12 parameters. If omitted, defaults match ``Case12Parameters()``,
        which is also the default used by the Fortran reference program.
    """

    if component not in CASE12_FIELD_COMPONENTS:
        raise ValueError(
            f"component must be one of {CASE12_FIELD_COMPONENTS!r}, got {component!r}."
        )

    params = parameters or Case12Parameters()

    def evaluator(grid: Grid2D) -> np.ndarray:
        fields = evaluate_case_12_exact(grid, t=t, parameters=params)
        value = getattr(fields, component)
        if value is None:
            raise ValueError(f"Field component {component!r} was not computed.")
        return value

    return compare_case12_reference_csv(
        path,
        component=component,
        evaluator=evaluator,
        atol=atol,
        rtol=rtol,
    )


def compare_case12_euler_step_reference(
    path: str | Path,
    *,
    component: str,
    field_parameters: Case12Parameters | None = None,
    source_parameters: Case12SourceTermParameters | None = None,
    step_parameters: EulerStepParameters | None = None,
    atol: float = 1.0e-10,
    rtol: float = 1.0e-10,
) -> SourceTermReferenceComparison:
    """Compare one Case 12 field after one explicit Euler step against a Fortran-generated CSV.

    Parameters
    ----------
    path:
        Reference CSV with columns ``x,y,wz,txx,txy,tyy`` (post-step values),
        generated by
        ``validation/fortran_reference/case12_euler_step/case12_euler_step_reference.f90``.
    component:
        Field component to compare. Must be one of
        ``CASE12_EULER_STEP_COMPONENTS``.
    field_parameters, source_parameters:
        Parameters for the ``t=0`` exact fields and source terms. If omitted,
        defaults match ``Case12Parameters()`` and
        ``Case12SourceTermParameters()``, which are also the defaults used by
        the input CSV generator
        (``validation/fortran_reference/case12_euler_step/generate_input_csv.py``).
    step_parameters:
        Euler-step parameters. If omitted, defaults match
        ``EulerStepParameters()``, which is also the default used by the
        Fortran reference program.
    """

    if component not in CASE12_EULER_STEP_COMPONENTS:
        raise ValueError(
            f"component must be one of {CASE12_EULER_STEP_COMPONENTS!r}, got {component!r}."
        )

    fields_params = field_parameters or Case12Parameters()
    source_params = source_parameters or Case12SourceTermParameters()
    step_params = step_parameters or EulerStepParameters()

    def evaluator(grid: Grid2D) -> np.ndarray:
        fields = evaluate_case_12_exact(grid, t=0.0, parameters=fields_params)
        source_terms = evaluate_case_12_source_terms(grid, t=0.0, parameters=source_params)

        u = _require_array(fields.u, "u")
        v = _require_array(fields.v, "v")
        wz = _require_array(fields.wz, "wz")
        txx = _require_array(fields.txx, "txx")
        txy = _require_array(fields.txy, "txy")
        tyy = _require_array(fields.tyy, "tyy")
        tfwz = _require_array(source_terms.tfwz, "tfwz")
        tftxx = _require_array(source_terms.tfTxx, "tfTxx")
        tftxy = _require_array(source_terms.tfTxy, "tfTxy")
        tftyy = _require_array(source_terms.tfTyy, "tfTyy")

        wz_new = euler_step_wz(wz, txx, txy, tyy, u, v, tfwz, grid, step_params)
        txx_new, txy_new, tyy_new = euler_step_stress(
            txx, txy, tyy, u, v, tftxx, tftxy, tftyy, grid, step_params
        )

        return {"wz": wz_new, "txx": txx_new, "txy": txy_new, "tyy": tyy_new}[component]

    return compare_case12_reference_csv(
        path,
        component=component,
        evaluator=evaluator,
        atol=atol,
        rtol=rtol,
    )


def compare_case12_log_euler_step_reference(
    path: str | Path,
    *,
    component: str,
    t: float = 0.3,
    field_parameters: Case12Parameters | None = None,
    source_parameters: Case12SourceTermParameters | None = None,
    step_parameters: EulerStepParameters | None = None,
    atol: float = 1.0e-10,
    rtol: float = 1.0e-10,
) -> SourceTermReferenceComparison:
    """Compare one Case 12 field after one log-conformation Euler step against a Fortran CSV.

    Parameters
    ----------
    path:
        Reference CSV with columns ``x,y,wz,txx,txy,tyy`` (post-step values,
        ``txx``/``txy``/``tyy`` recovered from the post-step ``Psi``),
        generated by
        ``validation/fortran_reference/case12_log_euler_step/case12_log_euler_step_reference.f90``.
    component:
        Field component to compare. Must be one of
        ``CASE12_LOG_EULER_STEP_COMPONENTS``.
    t:
        Evaluation time for the exact fields and source terms. Defaults to
        ``0.3``, matching
        ``case12_log_euler_step/generate_input_csv.py`` (``t=0`` makes the
        Case 12 polymeric stress identically zero, a degenerate
        repeated-eigenvalue case).
    field_parameters, source_parameters:
        Parameters for the exact fields and source terms. If omitted,
        defaults match ``Case12Parameters()`` and
        ``Case12SourceTermParameters()``.
    step_parameters:
        Euler-step parameters. If omitted, defaults match
        ``EulerStepParameters()``, which is also the default used by the
        Fortran reference program.
    """

    if component not in CASE12_LOG_EULER_STEP_COMPONENTS:
        raise ValueError(
            f"component must be one of {CASE12_LOG_EULER_STEP_COMPONENTS!r}, got {component!r}."
        )

    fields_params = field_parameters or Case12Parameters()
    source_params = source_parameters or Case12SourceTermParameters()
    step_params = step_parameters or EulerStepParameters()
    etap = (1.0 - step_params.beta) / (step_params.reynolds * step_params.wi)

    def evaluator(grid: Grid2D) -> np.ndarray:
        fields = evaluate_case_12_exact(grid, t=t, parameters=fields_params)
        source_terms = evaluate_case_12_source_terms(grid, t=t, parameters=source_params)

        u = _require_array(fields.u, "u")
        v = _require_array(fields.v, "v")
        wz = _require_array(fields.wz, "wz")
        txx = _require_array(fields.txx, "txx")
        txy = _require_array(fields.txy, "txy")
        tyy = _require_array(fields.tyy, "tyy")
        tfwz = _require_array(source_terms.tfwz, "tfwz")
        tftxx = _require_array(source_terms.tfTxx, "tfTxx")
        tftxy = _require_array(source_terms.tfTxy, "tfTxy")
        tftyy = _require_array(source_terms.tfTyy, "tfTyy")

        psixx, psixy, psiyy = stress_to_log_conformation(txx, txy, tyy, etap=etap)
        tf_psixx, tf_psixy, tf_psiyy = tftxx / etap, tftxy / etap, tftyy / etap

        wz_new, psixx_new, psixy_new, psiyy_new = euler_step_log_conformation(
            wz, psixx, psixy, psiyy, u, v, tfwz, tf_psixx, tf_psixy, tf_psiyy, grid, step_params
        )
        txx_new, txy_new, tyy_new = log_conformation_to_stress(
            psixx_new, psixy_new, psiyy_new, etap=etap
        )

        return {"wz": wz_new, "txx": txx_new, "txy": txy_new, "tyy": tyy_new}[component]

    return compare_case12_reference_csv(
        path,
        component=component,
        evaluator=evaluator,
        atol=atol,
        rtol=rtol,
    )


def compare_case12_time_step_reference(
    path: str | Path,
    *,
    component: str,
    field_parameters: Case12Parameters | None = None,
    source_parameters: Case12SourceTermParameters | None = None,
    step_parameters: EulerStepParameters | None = None,
    atol: float = 1.0e-10,
    rtol: float = 1.0e-10,
) -> SourceTermReferenceComparison:
    """Compare one Case 12 field after one full time-marching step against a Fortran-generated CSV.

    Parameters
    ----------
    path:
        Reference CSV with columns ``x,y,wz,txx,txy,tyy,psi,u,v`` (post-step
        values), generated by
        ``validation/fortran_reference/case12_time_step/case12_time_step_reference.f90``.
    component:
        Field component to compare. Must be one of
        ``CASE12_TIME_STEP_COMPONENTS``.
    field_parameters, source_parameters:
        Parameters for the ``t=0`` exact fields and source terms. If omitted,
        defaults match ``Case12Parameters()`` and
        ``Case12SourceTermParameters()``, which are also the defaults used by
        the input CSV generator
        (``validation/fortran_reference/case12_time_step/generate_input_csv.py``).
    step_parameters:
        Euler-step parameters. If omitted, defaults match
        ``EulerStepParameters()``, which is also the default used by the
        Fortran reference program.
    """

    if component not in CASE12_TIME_STEP_COMPONENTS:
        raise ValueError(
            f"component must be one of {CASE12_TIME_STEP_COMPONENTS!r}, got {component!r}."
        )

    fields_params = field_parameters or Case12Parameters()
    source_params = source_parameters or Case12SourceTermParameters()
    step_params = step_parameters or EulerStepParameters()

    def evaluator(grid: Grid2D) -> np.ndarray:
        fields = evaluate_case_12_exact(grid, t=0.0, parameters=fields_params)

        state = TimeMarchingState(
            u=_require_array(fields.u, "u"),
            v=_require_array(fields.v, "v"),
            wz=_require_array(fields.wz, "wz"),
            psi=_require_array(fields.psi, "psi"),
            txx=_require_array(fields.txx, "txx"),
            txy=_require_array(fields.txy, "txy"),
            tyy=_require_array(fields.tyy, "tyy"),
        )

        new_state = case12_time_step(
            state,
            t=0.0,
            grid=grid,
            step_parameters=step_params,
            field_parameters=fields_params,
            source_parameters=source_params,
        )

        return {
            "wz": new_state.wz,
            "txx": new_state.txx,
            "txy": new_state.txy,
            "tyy": new_state.tyy,
            "psi": new_state.psi,
            "u": new_state.u,
            "v": new_state.v,
        }[component]

    return compare_case12_reference_csv(
        path,
        component=component,
        evaluator=evaluator,
        atol=atol,
        rtol=rtol,
    )


def compare_case12_multistep_reference(
    path: str | Path,
    *,
    n_steps: int,
    component: str,
    field_parameters: Case12Parameters | None = None,
    source_parameters: Case12SourceTermParameters | None = None,
    step_parameters: EulerStepParameters | None = None,
    atol: float = 1.0e-10,
    rtol: float = 1.0e-10,
) -> SourceTermReferenceComparison:
    """Compare one Case 12 field after ``n_steps`` time-marching steps against a Fortran-generated CSV.

    Parameters
    ----------
    path:
        Reference CSV with columns ``x,y,wz,txx,txy,tyy,psi,u,v`` (values
        after ``n_steps`` full time-marching steps), generated by
        ``validation/fortran_reference/case12_multistep/case12_multistep_reference.f90``.
    n_steps:
        Number of full time-marching steps, starting from the ``t=0`` exact
        fields. Must match the ``n_steps`` used to generate ``path``.
    component:
        Field component to compare. Must be one of
        ``CASE12_TIME_STEP_COMPONENTS``.
    field_parameters, source_parameters:
        Parameters for the ``t=0`` exact fields and source terms. If omitted,
        defaults match ``Case12Parameters()`` and
        ``Case12SourceTermParameters()``, which are also the defaults used by
        the input CSV generator
        (``validation/fortran_reference/case12_time_step/generate_input_csv.py``).
    step_parameters:
        Euler-step parameters. If omitted, defaults match
        ``EulerStepParameters()``, which is also the default used by the
        Fortran reference program.
    """

    if component not in CASE12_TIME_STEP_COMPONENTS:
        raise ValueError(
            f"component must be one of {CASE12_TIME_STEP_COMPONENTS!r}, got {component!r}."
        )

    fields_params = field_parameters or Case12Parameters()
    source_params = source_parameters or Case12SourceTermParameters()
    step_params = step_parameters or EulerStepParameters()

    def evaluator(grid: Grid2D) -> np.ndarray:
        fields = evaluate_case_12_exact(grid, t=0.0, parameters=fields_params)

        state = TimeMarchingState(
            u=_require_array(fields.u, "u"),
            v=_require_array(fields.v, "v"),
            wz=_require_array(fields.wz, "wz"),
            psi=_require_array(fields.psi, "psi"),
            txx=_require_array(fields.txx, "txx"),
            txy=_require_array(fields.txy, "txy"),
            tyy=_require_array(fields.tyy, "tyy"),
        )

        final_state = case12_multistep_march(
            state,
            t0=0.0,
            n_steps=n_steps,
            grid=grid,
            step_parameters=step_params,
            field_parameters=fields_params,
            source_parameters=source_params,
        )

        return {
            "wz": final_state.wz,
            "txx": final_state.txx,
            "txy": final_state.txy,
            "tyy": final_state.tyy,
            "psi": final_state.psi,
            "u": final_state.u,
            "v": final_state.v,
        }[component]

    return compare_case12_reference_csv(
        path,
        component=component,
        evaluator=evaluator,
        atol=atol,
        rtol=rtol,
    )


